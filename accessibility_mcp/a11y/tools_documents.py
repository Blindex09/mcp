def register_documents(mcp: Any) -> None:
    @mcp.tool(annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=False, idempotentHint=False, openWorldHint=False))
    async def a11y_create_document(document: DocumentSpec, formats: Formats = "both") -> str:
        """Generate actual accessible DOCX and tagged PDF files, not just text or instructions, whenever the person asks for an accessible document.
        You write the content in document: title, language, author, subject, toc (optional automatic linked contents), blocks (kind paragraph/heading/list/table/image/link/field).
        Heading levels start at 2 (the title is level 1); tables require text (caption), headers and rows; images require source (local PNG/JPEG
        in the chosen workspace) and alt. Headings can have id; links require text and url (http/https/mailto or #heading_id).
        Fields require field_name, text label, help_text; field_type text|checkbox|choice, required, value or checked, options for choice.
        DOCX has native content controls; PDF has tagged fillable AcroForm widgets. No submission, macros or signatures.
        Read document-behavior-matrix for contracts and limitations. Never fetch remote images. formats: docx | pdf | both.
        Optional assessments contain criterion, status, coverage, evidence and remarks decided by YOU from actual evaluation.
        Supports is never inferred from no findings or severity; incomplete evaluation stays Not Evaluated.
        Files are generated in the user's document store with unique names, without overwriting project files. Return the paths and resource URIs
        to the person. Read the validation result, repair failures and state human checks still pending; no automatic check certifies conformance."""
        try:
            return json.dumps(await documents.create(document, formats), ensure_ascii=False)
        except Exception as e:  # noqa: BLE001 - fronteira MCP com erro explicito
            return json.dumps({"error": f"{type(e).__name__}: {e}"}, ensure_ascii=False)

    @mcp.tool(annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=False, idempotentHint=True, openWorldHint=False))
    async def a11y_validate_document(path: str, external: bool = True) -> str:
        """Validate an actual DOCX, PDF, XLSX or PPTX file in the chosen workspace or generated by this server.
        DOCX and PDF checks include document structure; XLSX inspects tables, declared headers, frozen panes and defined names
        without requiring audit-report sheets. Frozen panes do not prove header associations or screen-reader speech;
        PPTX checks slide titles, text and language metadata. external=True also invokes veraPDF for PDF when installed.
        Missing validators are not_run, never passed. These are structural checks, not a complete semantic, visual or
        assistive-technology evaluation. State exactly what remains for human review."""
        try:
            return json.dumps(await validate(documents.resolve_input(path), external), ensure_ascii=False)
        except Exception as e:  # noqa: BLE001 - fronteira MCP com erro explicito
            return json.dumps({"error": f"{type(e).__name__}: {e}"}, ensure_ascii=False)

    @mcp.tool(annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=False, idempotentHint=False, openWorldHint=False))
    async def a11y_create_report(
        formats: Literal["docx", "pdf", "both", "xlsx", "pptx", "all"] = "both",
        run_id: str = "",
        title: str = "Relatório de avaliação de acessibilidade",
        language: Literal["pt", "pt-BR", "pt-PT"] = "pt-BR",
        run_ids: list[str] | None = None,
        report_context: ReportContext | None = None,
        allow_incomplete: bool = False,
    ) -> str:
        """Create a plain-language accessibility report as DOCX, tagged PDF, structured XLSX or structured PPTX.
        The narrative is written in simple Portuguese for the person who will fix the code and for the person affected by the problem.
        Each finding is a five-part card — where it is on screen (in words, not a class name), what was measured,
        why it fails the criterion, how to reproduce (when recorded) and how to fix it — and the criterion number,
        level and priority stay visible for QA. Write claim, recommendation, observed, expected and rationale with a11y_finding:
        the report quotes them; the server never invents text.
        Use the current session or provide one run_id or several run_ids to combine pages. Each issue includes its WCAG principle,
        guideline and criterion, criticality, priority, affected page, observed element, CSS selector when available,
        impact and suggested correction. Repeated issues are grouped with the number and URLs of affected pages.
        Formats: docx | pdf | both (DOCX and PDF) | xlsx | pptx | all. Missing location or recommendation is stated, never invented.
        No findings never means conformance. Return file paths and resource URIs; disclose structural checks and remaining human review.

        report_context optionally records evaluator, commissioner, product/report versions, evaluation period, actual methods,
        environment and assistive technology versions, operating_system, browsers, sampling rationale, complete processes and exclusions.
        Its findings list attaches reproduction_steps, expected_result, actual_result,
        environment, owner, due_date, ticket and retest to exact finding_id values.
        Preconditions, evidence, retest evidence and trace step numbers are not displayed in generated report files.
        Existing evidence fields remain accepted for internal validation and compatibility; never copy their contents into narrative fields.
        It also accepts code_snippet (observed source), detected_on and fix_applied (change and build).
        For each occurrence include problem_location, shown as Roteiro: the exact human-readable location of the barrier.
        Identify the page, section or form, element type and actual link text, heading text or field label.
        Distinguish repeated names using their surrounding context. Example: Home page > footer > Company section > Contact Us link.
        Describe only observed facts; if unavailable, disclose the missing location. A generic task such as "open the menu"
        is not a location. journey remains the task/journey, and reproduction_steps remains the sequence of actions.
        Read report-writing-style for precise accessible routes. The findings also accept reproduction_steps_visual,
        reproduction_steps_keyboard and reproduction_steps_screen_reader, as ordered lists of actually observed actions.
        For a requested reader route that was not executed, use reproduction_steps_screen_reader_proposed instead.
        It is displayed explicitly as unexecuted navigation guidance; it never counts as a tested route or criterion evidence.
        Supply reader/browser/mode, starting point, documented commands and exact observed target names/roles.
        REPORT TEMPLATE (xlsx, docx and pdf follow the same model; fill these fields so nothing is left blank or invented):
        (1) ONE SCREEN = ONE SHEET in the xlsx and one section in the docx/pdf: set `screen` on each finding (FindingDetails.screen, or
        a11y_finding screen=...; 'Todas as telas' for what repeats everywhere) and list the tested screens in report_context.screens
        (name, description, items[{item, detail}]) in the order of the tabs; a tested screen with no finding keeps its own sheet with what was
        tested, not tested and observed. There is no aggregated findings sheet.
        (2) Steps are two separate cells: 'com visão' (a person with low vision or accessibility QA: what to open, look at, click, press with the
        keyboard while watching the focus ring; fields reproduction_steps, reproduction_steps_visual, reproduction_steps_keyboard) and 'sem visão'
        (a person who really uses a screen reader and does not see the screen: reproduction_steps_screen_reader with the exact keys pressed — Tab,
        Shift+Tab, Enter, arrows, browse-mode letters such as D, B, K, E, H, Ctrl+Home — and the exact speech the reader said, only for what was
        executed; unexecuted guidance goes in reproduction_steps_screen_reader_proposed and is labeled 'Roteiro sugerido: NÃO foi executado').
        Every key and every speech written must have been executed and read on the real reader; check them before writing.
        (3) Code in separate cells: code_snippet = the real problematic code (HTML, JS or CSS) copied from the page or its bundle with the origin
        (file URL and approximate position); fixed_code = the suggested corrected code, never applied or tested on the site unless stated; design_impact = what the fix changes visually ("Nenhum" or "Visual mínimo: ..."), column "Impacto no design".
        Also fill environment, testing_method, detected_on and a describable element/selector (never a tool-only selector like :has-text).
        These appear under Com visão, Por teclado and Com leitor de tela within Passos para reproduzir in every report format.
        Include URL/initial state, unambiguous target name and context, actions/keys actually used and what to check.
        Preserve visible-text/accessibility-name differences. Never invent Tab counts or screen-reader commands/speech,
        and never present an unexecuted alternative route as tested; disclose testing limits in method/coverage.
        Page titles are not displayed as a report field. Legacy page_title data remains accepted internally.
        Also include journey,
        testing_method, criterion_rationale, and operating_system/browsers when they differ from the report context.
        status is the declared remediation status; retest_date, retest_version, retest_evaluator, retest_result and retest_evidence
        keep retest facts separate. A fix description alone never means the issue was validated.
        Metadata includes product_name/description, report_date/modified, evaluation_goal, evaluator_organization/contact/expertise
        and content_languages. samples records each page/view with URL, title, journey, selection_reason, testing_method and environment.
        For multiple saved runs use finding_id '<run_id>:<original_id>'; ambiguous or unknown IDs are rejected.
        Only supply observed facts or explicitly agreed plans; missing information remains unrecorded. Do not put credentials in reports.
        report_context.criteria accepts evaluator-declared criterion results (passed/failed/cantTell/inapplicable/untested),
        scope, remarks, evidence and complete coverage. passed/inapplicable require complete=True and evidence;
        they cannot contradict unresolved failed/cantTell findings. This is a scoped test result, not a product certification.

        Estrutura entregue (template W3C WAI e WCAG-EM Step 5; nao e um ACR/VPAT):
        DOCX/PDF: identificacao inicial, resumo executivo, contexto da avaliacao, escopo, avaliadores, processo de avaliacao,
        resultados e acoes recomendadas (fichas por ocorrencia, matriz WCAG, cobertura, plano) e referencias.
        XLSX, nesta ordem: SOMENTE uma aba por tela testada; não há abas de resumo, escopo, matriz WCAG, correções e retestes nem referências.
        Each screen sheet has headers in row 1: Site in A1, Sistema operacional in B1, Navegadores in C1, then the other fields; a tested screen
        without findings has an Item/Detalhe sheet instead. Each occurrence occupies one data row below the headers. Table filters select rows;
        headers and the first three columns stay frozen. Steps are two columns (com visão; sem visão, for screen reader users) and the observed
        code and the suggested corrected code are two separate columns.
        Field order:
        site, operating system, browsers, principle, guideline, criticidade, priority and roteiro;
        then ID, page URL, criterion, level, situation, problem, recommended fix, why it fails,
        environment, method, element, selector, observed result, expected result,
        reproduction steps (com visão, sem visão), observed code, suggested corrected code, and design impact.
        Group IDs preserve recurring issues without mixing page-specific facts.
        Word and PDF repeat identification and triage as a two-column "Ficha do achado" table for each occurrence before its narrative.
        Prazos dependem de acordo; prioridade nao cria automaticamente um SLA.

        HOUSE RULE (enforced, for xlsx, docx, pdf and pptx): nothing goes out unconfirmed and nothing goes out missing. The report is NOT generated while a11y_lint_report would list errors (in Word and PDF every sentence or cell that would say "Não registrado", "Não informado" or "A definir" is an error too): a finding still
        "cantTell", any column that would stay "Não registrado", observed code not found exactly in the served file or shortened with "…", a fix not tested with a11y_try_patch,
        design impact not stated, a screen without a name or content, screen-reader steps not executed with the real NVDA (or not declared "Não se aplica" with the reason).
        The error returns the list; fix it and call again. allow_incomplete=true exists only for when the PERSON explicitly asks for an incomplete draft."""
        try:
            selected_formats = {
                "docx": ("docx",), "pdf": ("pdf",), "both": ("docx", "pdf"),
                "xlsx": ("xlsx",), "pptx": ("pptx",), "all": ("docx", "pdf", "xlsx", "pptx"),
            }[formats]
            requested_runs = list(dict.fromkeys(([run_id] if run_id else []) + (run_ids or [])))
            if run_id and run_ids:
                raise ValueError("Use run_id ou run_ids, não os dois.")
            if requested_runs:
                loaded = []
                for requested in requested_runs:
                    saved = runs.load(requested)
                    if saved is None:
                        raise ValueError(f"Execução '{requested}' não encontrada; consulte a11y_runs.")
                    saved_findings = []
                    for item in saved.get("findings", []):
                        copied = dict(item)
                        copied.setdefault("page_url", saved.get("url"))
                        copied["run_id"] = requested
                        copied["original_id"] = str(item.get("id") or "Não registrado")
                        if len(requested_runs) > 1:
                            copied["id"] = f"{requested}:{item.get('id', '')}"
                        saved_findings.append(copied)
                    loaded.append((saved, saved_findings))
                record = {
                    **loaded[0][0],
                    "url": loaded[0][0].get("url", ""),
                    "urls": list(dict.fromkeys(str(saved.get("url") or "") for saved, _ in loaded if saved.get("url"))),
                    "persona": ", ".join(dict.fromkeys(str(saved.get("persona") or "não informada") for saved, _ in loaded)),
                    "created": loaded[-1][0].get("created"),
                    "findings": [item for _, items in loaded for item in items],
                    "coverage": {
                        **((loaded[0][0].get("coverage") or {}) if len(loaded) == 1 else {}),
                        "gaps": list(dict.fromkeys(str(gap) for saved, _ in loaded for gap in (saved.get("coverage") or {}).get("gaps", []))),
                        "pages_visited": list(dict.fromkeys(str(saved.get("url") or "") for saved, _ in loaded if saved.get("url"))),
                        "browser": ", ".join(dict.fromkeys(str((saved.get("coverage") or {}).get("browser") or "não informado") for saved, _ in loaded)),
                        "probes_run": list(dict.fromkeys(str(probe) for saved, _ in loaded for probe in (saved.get("coverage") or {}).get("probes_run", []))),
                        "stress_run": list(dict.fromkeys(str(probe) for saved, _ in loaded for probe in (saved.get("coverage") or {}).get("stress_run", []))),
                    },
                }
            else:
                async with SESSION.lock:
                    page = SESSION._need()
                    record = {"url": page.url, "persona": SESSION.persona, "findings": list(SESSION.findings), "coverage": SESSION.coverage_report()}
            record = apply_context(record, report_context)
            quality = report_lint.lint(record, selected_formats, title, language)
            if not quality["ok"] and not allow_incomplete:
                # REGRA DA CASA: nada vai sem confirmacao e nada vai faltando. O relatorio nao e' gerado; a lista diz o que corrigir.
                return json.dumps({
                    "error": "relatorio NAO gerado: " + quality["summary"] + ". Corrija cada item de `lint.issues` (a11y_verify_code, a11y_try_patch, a11y_nvda_do, a11y_finding) e gere de novo. "
                             "So use allow_incomplete=true se a PESSOA pedir, explicitamente, um rascunho incompleto.",
                    "lint": quality,
                }, ensure_ascii=False)
            fingerprint = documents.report_fingerprint(record, title, selected_formats, language)
            previous = documents.existing_report(fingerprint)
            if previous is not None:
                # REGRA DA CASA: o mesmo relatorio nao e' gerado duas vezes, nem com outro nome nem "acrescentado": devolve o que ja existe.
                return json.dumps({**previous, "reused": True, "lint": quality,
                                   "notice": "Relatorio identico ao ja gerado: NAO criei outro arquivo. Use os arquivos de `files`. Se o conteudo mudar, o mesmo titulo gera de novo o mesmo arquivo, "
                                             "substituindo o anterior: o mais recente prevalece e nunca ficam dois com o mesmo nome."}, ensure_ascii=False)
            output: dict[str, Any] = {"files": []}
            document_formats = tuple(kind for kind in selected_formats if kind in ("docx", "pdf"))
            artifact_formats = tuple(kind for kind in selected_formats if kind in ("xlsx", "pptx"))
            if document_formats:
                content = documents.report_spec(record, title, language)
                document_format_by_formats: dict[tuple[str, ...], Formats] = {
                    ("docx",): "docx",
                    ("pdf",): "pdf",
                    ("docx", "pdf"): "both",
                }
                document_format = document_format_by_formats[document_formats]
                generated = await documents.create(content, document_format, documents.report_id("document:" + document_format, title, language))
                output["document_id"] = generated["document_id"]
                output.setdefault("document_ids", {}).update({kind: generated["document_id"] for kind in document_formats})
                output["files"].extend(generated["files"])
            if artifact_formats:
                artifact_id = documents.report_id("artifact:" + ",".join(sorted(artifact_formats)), title, language)
                artifact_folder = documents.fresh_folder(artifact_id)
                files = await asyncio.to_thread(report_artifacts.create, record, title, artifact_formats, artifact_folder, language)
                for entry in files:
                    entry["uri"] = f"a11y://document/{artifact_id}/{entry['filename']}"
                output.setdefault("document_ids", {}).update({kind: artifact_id for kind in artifact_formats})
                (artifact_folder / "validation.json").write_text(json.dumps(files, ensure_ascii=False, indent=2), encoding="utf-8")
                output.setdefault("document_id", artifact_id)
                output["files"].extend(files)
            output["lint"] = quality
            documents.remember_report(fingerprint, output)
            return json.dumps(output, ensure_ascii=False)
        except Exception as e:  # noqa: BLE001 - fronteira MCP com erro explicito
            return json.dumps({"error": f"{type(e).__name__}: {e}"}, ensure_ascii=False)

    @mcp.tool(annotations=ToolAnnotations(readOnlyHint=True, destructiveHint=False, idempotentHint=True, openWorldHint=False))
    async def a11y_lint_report(run_id: str = "", run_ids: list[str] | None = None, formats: Literal["docx", "pdf", "both", "xlsx", "pptx", "all"] = "all") -> str:
        """CHECK A REPORT BEFORE DELIVERING IT. Reads the findings of the current session (or of saved runs) and lists what a reviewer would point out: observed code
        missing, shortened with "…" or not found exactly in the real file, fix not tested in the browser, design impact not stated, screen without a name, screen-reader
        steps without an executed NVDA step cited. Each item has finding, rule, severity (erro | aviso | info) and message. Nothing is changed or blocked: fix the
        findings (a11y_verify_code, a11y_try_patch, a11y_finding) and call again. a11y_create_report also returns this list as `lint`."""
        try:
            wanted = list(dict.fromkeys(([run_id] if run_id else []) + (run_ids or [])))
            findings: list[dict[str, Any]] = []
            if wanted:
                for name in wanted:
                    saved = runs.load(name)
                    if saved is None:
                        raise ValueError(f"Execução '{name}' não encontrada; consulte a11y_runs.")
                    findings.extend(saved.get("findings", []))
            else:
                async with SESSION.lock:
                    SESSION._need()
                    findings = list(SESSION.findings)
            kinds = {"docx": ("docx",), "pdf": ("pdf",), "both": ("docx", "pdf"), "xlsx": ("xlsx",), "pptx": ("pptx",), "all": ("docx", "pdf", "xlsx", "pptx")}[formats]
            return json.dumps(report_lint.lint({"findings": findings}, kinds), ensure_ascii=False)
        except Exception as e:  # noqa: BLE001 - fronteira MCP com erro explicito
            return json.dumps({"error": f"{type(e).__name__}: {e}"}, ensure_ascii=False)

    @mcp.resource("a11y://document/{document_id}/document.pdf", mime_type="application/pdf")
    def a11y_pdf_resource(document_id: str) -> bytes:
        """Download the generated PDF bytes; only generated artifacts can be read."""
        return documents.artifact_path(document_id, "document.pdf").read_bytes()

    @mcp.resource("a11y://document/{document_id}/document.docx", mime_type=documents.MIMES["docx"])
    def a11y_docx_resource(document_id: str) -> bytes:
        """Download the generated DOCX bytes; only generated artifacts can be read."""
        return documents.artifact_path(document_id, "document.docx").read_bytes()

    @mcp.resource("a11y://document/{document_id}/report.xlsx", mime_type=documents.MIMES["report.xlsx"])
    def a11y_xlsx_resource(document_id: str) -> bytes:
        """Download the generated accessible spreadsheet; only generated artifacts can be read."""
        return documents.artifact_path(document_id, "report.xlsx").read_bytes()

    @mcp.resource("a11y://document/{document_id}/report.pptx", mime_type=documents.MIMES["report.pptx"])
    def a11y_pptx_resource(document_id: str) -> bytes:
        """Download the generated structured presentation; only generated artifacts can be read."""
        return documents.artifact_path(document_id, "report.pptx").read_bytes()
