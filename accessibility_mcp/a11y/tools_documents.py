"""Documentos e relatorios disponiveis a qualquer cliente MCP, inclusive sem terminal."""

from __future__ import annotations

import json
from typing import Any, Literal

from mcp.types import ToolAnnotations

from . import documents, runs
from .document_schema import DocumentSpec
from .document_validation import validate
from .documents import Formats
from .session import SESSION


def register_documents(mcp: Any) -> None:
    @mcp.tool(annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=False, idempotentHint=False, openWorldHint=False))
    async def a11y_create_document(document: DocumentSpec, formats: Formats = "both") -> str:
        """Generate actual accessible DOCX and tagged PDF files, not just text or instructions, whenever the person asks for an accessible document.
        You write the content in document: title, language, author, subject, blocks (kind paragraph/heading/list/table/image/link).
        Heading levels start at 2 (the title is level 1); tables require text (caption), headers and rows; images require source (local PNG/JPEG
        in the chosen workspace) and alt. Links require text and url. Never fetch remote images. formats: docx | pdf | both.
        Optional assessments contain criterion, status, coverage, evidence and remarks decided by YOU from actual evaluation.
        Supports is never inferred from no findings or severity; incomplete evaluation stays Not Evaluated.
        Files are generated in the user's document store with unique names, without overwriting project files. Return the paths and resource URIs
        to the person. Read the validation result, repair failures and state human checks still pending; no automatic check certifies conformance."""
        try:
            return json.dumps(await documents.create(document, formats), ensure_ascii=False)
        except Exception as e:  # noqa: BLE001 - fronteira MCP com erro explicito
            return json.dumps({"error": f"{type(e).__name__}: {e}"}, ensure_ascii=False)

    @mcp.tool(annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=False, idempotentHint=True, openWorldHint=False))
    async def a11y_validate_document(path: str, external: bool = True) -> str:
        """Validate an actual DOCX or PDF file in the chosen workspace or generated by this server. Checks title, language, heading order,
        image alt, table headers, links; PDF also checks tags, embedded fonts and Unicode maps. external=True also invokes veraPDF when installed
        (A11Y_MCP_VERAPDF can select its executable or executable JAR). Missing validator is not_run, never passed.
        This is structural validation, not a complete semantic, visual or assistive-technology evaluation. Tell the person exactly what remains."""
        try:
            return json.dumps(await validate(documents.resolve_input(path), external), ensure_ascii=False)
        except Exception as e:  # noqa: BLE001 - fronteira MCP com erro explicito
            return json.dumps({"error": f"{type(e).__name__}: {e}"}, ensure_ascii=False)

    @mcp.tool(annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=False, idempotentHint=False, openWorldHint=False))
    async def a11y_create_report(formats: Formats = "both", run_id: str = "", title: str = "Relatório de avaliação de acessibilidade", language: Literal["pt", "pt-BR", "pt-PT"] = "pt-BR") -> str:
        """Generate actual DOCX/PDF accessibility reports from the current session's measured findings and coverage, or a saved run_id.
        Use when the person asks for a report file. This standard report is written in Portuguese; for other languages write a custom document.
        This exports evidence, outcomes and limitations; no findings never means Supports.
        For a criterion-by-criterion conformance report, YOU assess the evidence and call a11y_create_document with explicit assessments.
        Criteria not fully evaluated must remain Not Evaluated. Return the file paths/resource URIs and disclose pending validation."""
        try:
            if run_id:
                record = runs.load(run_id)
                if record is None:
                    raise ValueError("Execucao nao encontrada; consulte a11y_runs.")
            else:
                async with SESSION.lock:
                    page = SESSION._need()
                    record = {"url": page.url, "persona": SESSION.persona, "findings": list(SESSION.findings), "coverage": SESSION.coverage_report()}
            return json.dumps(await documents.create(documents.report_spec(record, title, language), formats), ensure_ascii=False)
        except Exception as e:  # noqa: BLE001 - fronteira MCP com erro explicito
            return json.dumps({"error": f"{type(e).__name__}: {e}"}, ensure_ascii=False)

    @mcp.resource("a11y://document/{document_id}/document.pdf", mime_type="application/pdf")
    def a11y_pdf_resource(document_id: str) -> bytes:
        """Download the generated PDF bytes; only generated artifacts can be read."""
        return documents.artifact_path(document_id, "document.pdf").read_bytes()

    @mcp.resource("a11y://document/{document_id}/document.docx", mime_type=documents.MIMES["docx"])
    def a11y_docx_resource(document_id: str) -> bytes:
        """Download the generated DOCX bytes; only generated artifacts can be read."""
        return documents.artifact_path(document_id, "document.docx").read_bytes()
